export function errorText(reason: unknown, locale: UILocale): string {
  const err = reason as {code?: string; status?: number; name?: string} | undefined;
  if (err?.code && errorKeys[err.code]) return uiText(errorKeys[err.code], locale);
  if (err?.status === 401) return uiText("sessionExpired", locale);
  if (err?.status === 403) return uiText("permissionDenied", locale);
  if (err?.status && err.status >= 500) return uiText("unavailable", locale);
  if (err?.name === "TimeoutError" || err?.name === "AbortError") return uiText("timeout", locale);
  if (err instanceof TypeError) return uiText("networkError", locale);
  return uiText("requestFailed", locale);
}
export function browserLocale(): UILocale {
  if (typeof document !== "undefined" && document.documentElement.lang) return document.documentElement.lang.startsWith("ru") ? "ru" : "en";
  try { const stored = localStorage.getItem("home-ai-core.locale"); if (stored === "ru" || stored === "en") return stored; } catch { /* restricted browser storage */ }
  return typeof navigator !== "undefined" && (navigator.language || navigator.languages?.[0] || "en").startsWith("ru") ? "ru" : "en";
}
